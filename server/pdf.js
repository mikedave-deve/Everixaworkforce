/* ── Shipment invoice ────────────────────────────────────────── */
export function invoicePdf(s) {
  const ctx = start('Invoice', `No. ${s.invoiceNumber}`)
  const { doc } = ctx
  let y = ctx.y
  kv(doc, 'Invoice date', dateLong(s.createdAt), 48, y, 160)
  kv(doc, 'Tracking number', s.tracking, 220, y, 170)
  kv(doc, 'Service', s.service || 'Everixa Courier', 400, y, 147)
  y += 56
  eyebrow(doc, 'Ship from', 48, y)
  doc.fillColor(INK).font('Helvetica').fontSize(10.5).text([s.from?.name, s.from?.address, `${s.from?.city ?? ''}${s.from?.state ? `, ${s.from.state}` : ''} ${s.from?.zip ?? ''}`.trim()].filter(Boolean).join('\n'), 48, y + 14, { width: 230, lineGap: 3 })
  eyebrow(doc, 'Ship to', 310, y)
  doc.fillColor(INK).font('Helvetica').fontSize(10.5).text([s.to?.name, s.to?.address, `${s.to?.city ?? ''}${s.to?.state ? `, ${s.to.state}` : ''} ${s.to?.zip ?? ''}`.trim()].filter(Boolean).join('\n'), 310, y + 14, { width: 237, lineGap: 3 })
  y += 100

  // Items table
  doc.rect(48, y, 499, 26).fill(INK)
  doc.fillColor(BRASS_L).font('Helvetica-Bold').fontSize(7.5)
  doc.text('DESCRIPTION', 60, y + 9, { characterSpacing: 1.4 })
  doc.text('QTY', 340, y + 9, { width: 40, align: 'right', characterSpacing: 1.4 })
  doc.text('UNIT PRICE', 385, y + 9, { width: 70, align: 'right', characterSpacing: 1.4 })
  doc.text('AMOUNT', 460, y + 9, { width: 77, align: 'right', characterSpacing: 1.4 })
  y += 26
  let subtotal = 0
  for (const it of s.items ?? []) {
    const amount = it.qty * it.unitPrice
    subtotal += amount
    doc.fillColor(INK).font('Helvetica').fontSize(10).text(it.description, 60, y + 9, { width: 270 })
    doc.text(String(it.qty), 340, y + 9, { width: 40, align: 'right' })
    doc.text(money(it.unitPrice), 385, y + 9, { width: 70, align: 'right' })
    doc.text(money(amount), 460, y + 9, { width: 77, align: 'right' })
    doc.moveTo(48, y + 30).lineTo(547, y + 30).lineWidth(0.4).strokeColor(LINE).stroke()
    y += 31
  }
  y += 14
  const totals = [['Subtotal', subtotal], ['Shipping & handling', s.shippingCost ?? 0]]
  for (const [k, v] of totals) {
    doc.fillColor(MUTED).font('Helvetica').fontSize(10).text(k, 330, y, { width: 100, align: 'right' })
    doc.fillColor(INK).text(money(v), 440, y, { width: 97, align: 'right' })
    y += 20
  }
  doc.rect(330, y + 4, 217, 44).fill(INK)
  doc.fillColor(BRASS_L).font('Helvetica-Bold').fontSize(8).text('TOTAL DUE', 344, y + 21, { characterSpacing: 2 })
  doc.fillColor(IVORY).font('Times-Roman').fontSize(20).text(money(subtotal + (s.shippingCost ?? 0)), 400, y + 15, { width: 133, align: 'right' })
  y += 64
  if (s.reference) {
    doc.fillColor(MUTED).font('Helvetica').fontSize(9).text(`Reference: ${s.reference}`, 48, y)
  }
  return finish(ctx, 'Thank you for choosing Everixa Workforce.')
}
